"""Add original, word-timed sound design without changing the natural narration.

Run from the repo root:
    .venv/bin/python production/data-centres-natural/punchy_audio.py

Prerequisites: numpy, scipy, ffmpeg, ffprobe, plus the local voice.wav and
music.wav generated by build_audio.py. If those masters are absent, first run
that builder using the current narration. It requires edge-tts/network access.
This pass itself is offline. It never rewrites the voice, timeline or subtitles.

The MP3 is bundled for fresh-clone rendering. WAV intermediates stay under out/.
All effects are synthesized illustrations, not recordings of a real facility.
"""
from __future__ import annotations

import hashlib
import json
import math
import subprocess
from pathlib import Path

import numpy as np
from scipy import signal
from scipy.io import wavfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PUBLIC = ROOT / "public/data-centres-natural"
SCRATCH = ROOT / "out/data-centres/punchy-audio"
SR = 48_000
SEED = 81704


def run(*args: object) -> subprocess.CompletedProcess[str]:
    return subprocess.run([str(a) for a in args], check=True, capture_output=True, text=True)


def read_stereo(path: Path) -> np.ndarray:
    if not path.exists():
        raise FileNotFoundError(f"Missing {path}. Run build_audio.py first; see this file's docstring.")
    rate, pcm = wavfile.read(path)
    if rate != SR:
        raise ValueError(f"Expected {SR} Hz master: {path} has {rate}")
    if pcm.dtype != np.int16:
        raise ValueError(f"Expected int16 build_audio.py stem: {path}")
    data = pcm.astype(np.float64) / 32768
    return np.column_stack([data, data]) if data.ndim == 1 else data


def write_float(path: Path, samples: np.ndarray) -> None:
    wavfile.write(path, SR, samples.astype(np.float32))


def last_json(log: str) -> dict:
    return json.JSONDecoder().raw_decode(log[log.rfind("{"):])[0]


def main() -> None:
    SCRATCH.mkdir(parents=True, exist_ok=True)
    timeline = json.loads((HERE / "timeline.json").read_text())
    words = json.loads((HERE / "words.json").read_text())
    voice_path = PUBLIC / "voice.wav"
    voice = read_stereo(voice_path)
    music = read_stereo(HERE / "music.wav")
    n = round(timeline["totalDuration"] * SR)
    if len(voice) != n or len(music) != n:
        raise ValueError("Voice/music masters do not match timeline duration; rebuild native audio first.")
    if timeline["tempoFactor"] != 1 or timeline["rate"] != "+0%" or timeline["pitch"] != "+0Hz":
        raise ValueError("This soundtrack expects the approved native narration take.")
    rng = np.random.default_rng(SEED)
    time = np.arange(n) / SR
    effects = np.zeros_like(voice)
    percussion = np.zeros_like(voice)
    cues: list[dict] = []

    def word_time(phrase: str) -> float:
        tokens = phrase.lower().split()
        normalized = [w["word"].lower() for w in words]
        matches = [i for i in range(len(words) - len(tokens) + 1)
                   if normalized[i:i + len(tokens)] == tokens]
        if len(matches) != 1:
            raise ValueError(f"Expected unique measured phrase: {phrase!r}, got {len(matches)}")
        return words[matches[0]]["s"]

    def add(buffer: np.ndarray, sound: np.ndarray, start: float, gain: float, pan: float = 0) -> None:
        a = round(start * SR)
        if a < 0:
            sound, a = sound[-a:], 0
        b = min(n, a + len(sound))
        if b <= a:
            return
        x = sound[:b-a] * gain
        buffer[a:b, 0] += x * math.sqrt((1-pan)/2)
        buffer[a:b, 1] += x * math.sqrt((1+pan)/2)

    def tone(hz: float, duration: float = .16) -> np.ndarray:
        t = np.arange(round(duration * SR)) / SR
        return (np.sin(2*np.pi*hz*t) + .15*np.sin(2*np.pi*2*hz*t)) * np.exp(-t*24) * np.minimum(1, t/.004)

    def impact(duration: float = .26, hz: float = 72) -> np.ndarray:
        t = np.arange(round(duration * SR)) / SR
        # A short soft bass hit, not an explosive boom or clipping transient.
        x = np.sin(2*np.pi*(hz*t + 4*(1-np.exp(-t*25)))) * np.exp(-t*16)
        return x * np.minimum(1, t/.006) * np.minimum(1, (duration-t)/.025)

    def sweep(duration: float = .22) -> np.ndarray:
        t = np.arange(round(duration * SR)) / SR
        noise = signal.sosfilt(signal.butter(2, [400, 3200], fs=SR, btype="bandpass", output="sos"), rng.normal(size=len(t)))
        return noise * np.sin(np.pi*t/duration)**2

    def cue(phrase: str, kind: str, gain: float, pan: float = 0, offset: float = 0) -> None:
        start = word_time(phrase) + offset
        if kind == "reveal":
            add(effects, sweep(.26), start-.20, gain*.7, pan)
            add(effects, impact(), start, gain, pan)
        elif kind == "click":
            add(effects, tone(740, .12), start, gain, pan)
        elif kind == "rise":
            for step, hz in enumerate([349.23, 415.30, 523.25]):
                add(effects, tone(hz, .22), start+step*.09, gain, pan)
        elif kind == "drop":
            t = np.arange(round(.18*SR))/SR
            add(effects, np.sin(2*np.pi*(1200*t-2400*t*t))*np.exp(-t*30)*np.minimum(1,t/.003), start, gain, pan)
        elif kind == "brush":
            add(effects, sweep(.17), start-.08, gain, pan)
        else:
            raise ValueError(kind)
        cues.append({"phrase": phrase, "time": round(start, 4), "kind": kind,
                     "gain": gain, "pan": pan, "source": "measured words.json"})

    # The quiet first clause leaves room for the first concrete reveal to land.
    cue("cloud sounds", "click", .025, -.15)
    cue("Until", "brush", .065, -.2)
    cue("moves next door", "reveal", .13, .12)
    cue("personal", "click", .035, -.1)
    cue("real buildings", "reveal", .065, .1)
    cue("land", "click", .024, -.25)
    cue("power and", "click", .026, .25)
    cue("roughly double", "rise", .04, .05, word_time("double")-word_time("roughly double"))
    cue("grid cope", "brush", .055, -.2)
    cue("paying", "click", .032, .2)
    cue("use water", "drop", .045, -.2, word_time("water depending")-word_time("use water"))
    cue("design and location", "click", .025, .18)
    cue("demanded clearer answers", "brush", .055, -.15)
    cue("useful services", "rise", .028, .16)
    cue("investment", "click", .028, -.2)
    cue("tax revenue", "click", .024, .2)
    cue("the deal", "brush", .055, 0)
    for phrase, pan in [("transparent", -.2), ("noise controls", -.07), ("fair costs", .07), ("residents involved", .2)]:
        cue(phrase, "click", .031, pan)
    cue("neighbours aren't", "brush", .045, -.15)
    cue("a say", "rise", .035, .1, word_time("say")-word_time("a say"))

    # A short illustrated equipment hum appears only with the noise explanation.
    fan_start, fan_end = word_time("noise from"), word_time("homes") + .3
    tt = np.arange(round((fan_end-fan_start)*SR))/SR
    fan = (np.sin(2*np.pi*96*tt)+.27*np.sin(2*np.pi*192*tt))
    fan *= np.minimum(1,tt/.28)*np.minimum(1,(len(tt)/SR-tt)/.38)
    add(effects,fan,fan_start,.009,.22)
    cues.append({"phrase": "noise from ... homes", "time": round(fan_start,4),
                 "end": round(fan_end,4), "kind":"illustrative equipment hum", "gain":.009})

    # Keep the original score. Add a light rhythmic pulse, with fewer accents
    # during factual explanations and a small lift through benefits/payoff.
    bpm = 104
    beat = 60/bpm
    for b in range(math.ceil(timeline["totalDuration"]/beat)):
        at = word_time("moves next door")+b*beat
        if at >= timeline["totalDuration"]-1.1:
            break
        strength = .55 if 13.53 <= at < 47 else .85 if at < 55.6 else .65
        if b % 4 in (0,2):
            add(percussion,impact(.11,62),at,.027*strength)
        if b % 4 in (1,3):
            add(percussion,sweep(.055),at,.018*strength,.15)

    # Less bed under the first premise, physical noise illustration and final
    # question; restoration of the bed supplies contrast without faster speech.
    bed = np.interp(time,
        [0,1.65,1.97,3.5,4.1,34.75,35.75,39.9,40.6,47,55.6,64.77,67.4,68.05,70.70,71.2,72.2334],
        [.6,.6,.22,.22,1.0,1.0,.3,.3,.85,1.05,1,.85,.65,.38,.38,.8,0])
    music *= bed[:,None]
    # A symmetric short speech envelope ducks only the new backing layers.
    speech_power = signal.fftconvolve(np.mean(voice**2,axis=1), np.ones(2400)/2400, mode="same")
    duck = np.clip(1-np.sqrt(np.maximum(0,speech_power))*3.5,.40,1)
    effects *= duck[:,None]
    percussion *= duck[:,None]
    fade = np.minimum(1,(timeline["totalDuration"]-time)/.7)
    effects *= fade[:,None]
    percussion *= fade[:,None]
    premix = voice + music + effects + percussion
    voiced = speech_power > .0001
    voice_rms = np.sqrt(np.mean(voice[voiced]**2))
    backing_rms = np.sqrt(np.mean((music+effects+percussion)[voiced]**2))
    write_float(SCRATCH/"punchy-effects.wav",effects)
    write_float(SCRATCH/"punchy-percussion.wav",percussion)
    write_float(SCRATCH/"punchy-premix.wav",premix)

    analysis = last_json(run("ffmpeg","-hide_banner","-i",SCRATCH/"punchy-premix.wav","-af",
        "loudnorm=I=-16:TP=-1.5:LRA=8:print_format=json","-f","null","-").stderr)
    filt=(f"loudnorm=I=-16:TP=-1.5:LRA=8:measured_I={analysis['input_i']}:"
          f"measured_TP={analysis['input_tp']}:measured_LRA={analysis['input_lra']}:"
          f"measured_thresh={analysis['input_thresh']}:offset={analysis['target_offset']}:"
          "linear=true:print_format=json")
    # loudnorm's buffered tail can be shorter than the source. Normalize first,
    # then restore the exact timeline sample count, preserving the full speech.
    filt += f",aresample={SR},apad,atrim=end_sample={n}"
    master = run("ffmpeg","-y","-hide_banner","-i",SCRATCH/"punchy-premix.wav","-af",filt,
                 "-ar",SR,"-c:a","pcm_s24le",SCRATCH/"punchy-master.wav")
    run("ffmpeg","-y","-v","error","-i",SCRATCH/"punchy-master.wav","-c:a","libmp3lame","-q:a","2",PUBLIC/"punchy-mix.mp3")
    encoded_analysis = last_json(run("ffmpeg","-hide_banner","-i",PUBLIC/"punchy-mix.mp3","-af",
        "loudnorm=I=-16:TP=-1.5:LRA=8:print_format=json","-f","null","-").stderr)
    probe = json.loads(run("ffprobe","-v","error","-show_entries","format=duration:stream=codec_name,sample_rate,channels",
                          "-of","json",PUBLIC/"punchy-mix.mp3").stdout)
    run("ffmpeg","-y","-v","error","-i",PUBLIC/"punchy-mix.mp3","-c:a","pcm_s16le",SCRATCH/"punchy-decoded.wav")
    decoded_rate, decoded = wavfile.read(SCRATCH/"punchy-decoded.wav")
    if decoded_rate != SR or len(decoded) != n:
        raise ValueError(f"Encoded soundtrack decoded to {len(decoded)} samples at {decoded_rate}Hz; expected {n} at {SR}Hz")
    if float(encoded_analysis["input_tp"]) >= 0:
        raise ValueError("Encoded output clips")
    report = {
        "description":"Original word-timed accents and restrained rhythm; unchanged native narration timing and pitch",
        "seed":SEED,"bpm":bpm,"durationSeconds":timeline["totalDuration"],
        "sourceVoiceSha256":hashlib.sha256(voice_path.read_bytes()).hexdigest(),
        "sourceTimelineSha256":hashlib.sha256((HERE/"timeline.json").read_bytes()).hexdigest(),
        "sourceWordsSha256":hashlib.sha256((HERE/"words.json").read_bytes()).hexdigest(),
        "voiceTempoFactor":1.0,"voicePitchChangeHz":0,"voiceEdit":"No editing, stretching, resynthesis or pitch change; final mix mastering only",
        "voiceSamples":len(voice),"sampleRate":SR,"cues":cues,
        "decodedOutputSamples":len(decoded),"decodedOutputDurationSeconds":len(decoded)/SR,
        "premixVoiceToBackingDbDuringSpeech":round(float(20*np.log10(voice_rms/backing_rms)),2),
        "premixAnalysis":analysis,"mastering":last_json(master.stderr),
        "encodedMeasuredLUFS":float(encoded_analysis["input_i"]),
        "encodedMeasuredTruePeakDbTP":float(encoded_analysis["input_tp"]),
        "encodedMeasuredLRA":float(encoded_analysis["input_lra"]),
        "ffprobe":probe,"output":"public/data-centres-natural/punchy-mix.mp3",
        "qa":"Duration and loudness verified; review final film for cue/visual fit. Effects are illustrative synthesis, not field recordings.",
    }
    (HERE/"punchy-audio-report.json").write_text(json.dumps(report,indent=2)+"\n")
    print(json.dumps({k:report[k] for k in ["durationSeconds","encodedMeasuredLUFS","encodedMeasuredTruePeakDbTP","output"]},indent=2))


if __name__ == "__main__":
    main()
